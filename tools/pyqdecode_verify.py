"""Stage 5: verification report for the PYQ Decoding Manuals, from pyq.db (official papers).
Writes data/pyqdecode/verification_<g1|g2>.json and data/pyqdecode/VERIFICATION_REPORT.md. Lists:
key provenance per paper; deleted questions; key conflicts (key_note naming a conflict / disagreement); statements
whose truth is U or basis 'pending'; time-sensitive notes.
    python3 tools/pyqdecode_verify.py"""
import collections, json, re, sqlite3

con = sqlite3.connect("data/pyqdecode/pyq.db")
CONF = re.compile(r"conflict|disagree|differ|wrong|disput|contradict|but the app notes|app notes (say|give|credit)|possible error", re.I)
TIME = re.compile(r"time[- ]sensitive|as of|at the time|now |currently|since 20\d\d|updated|renamed|later changed|no longer", re.I)


def run(g, exam):
    papers = con.execute("""SELECT p.id, p.year, p.stage, p.title, p.key_status, p.key_doc_kind, count(q.id),
        sum(q.deleted), sum(q.key_check LIKE 'MATCH%'), sum(q.key_check LIKE 'CHANGED%' OR q.key_check LIKE 'DIFF%'),
        sum(q.key_check LIKE 'NO_OFFICIAL%' OR q.key_check LIKE 'NOT_IN_DOC%'), sum(q.key_check LIKE '%CONFLICT%')
        FROM paper p JOIN question q ON q.paper_id=p.id WHERE p.exam=? AND p.id NOT LIKE 'app:%' GROUP BY p.id ORDER BY p.year, p.id""",
                         (exam,)).fetchall()
    qs = con.execute("""SELECT q.id, p.year, q.text_original, q.key_text, q.key_note, q.deleted, q.key_check FROM question q
        JOIN paper p ON p.id=q.paper_id WHERE p.exam=? AND q.analysed IS NOT NULL ORDER BY q.id""", (exam,)).fetchall()
    st = con.execute("""SELECT s.question_id, s.label, s.text, s.truth, s.truth_basis, s.true_fact FROM statement s JOIN question q
        ON q.id=s.question_id JOIN paper p ON p.id=q.paper_id WHERE p.exam=? AND q.analysed IS NOT NULL
        AND (s.truth='U' OR s.truth_basis='pending') ORDER BY s.question_id""", (exam,)).fetchall()
    out = {"exam": exam,
           "papers": [dict(zip(("id", "year", "stage", "title", "key_status", "key_doc_kind", "Q", "deleted", "key_match",
                                "key_changed", "no_official_doc", "third_party_conflict"), [x if x is not None else 0 for x in r])) for r in papers],
           "deleted": [{"id": r[0], "stem": r[2][:200], "note": r[4]} for r in qs if r[5]],
           "conflicts": [{"id": r[0], "stem": r[2][:200], "key": r[3], "note": r[4]} for r in qs if r[4] and CONF.search(r[4]) and not r[5]],
           "unresolved": [{"id": r[0], "label": r[1], "text": r[2], "truth": r[3], "basis": r[4]} for r in st],
           "time_sensitive": [{"id": r[0], "year": r[1], "stem": r[2][:200], "note": r[4]} for r in qs if r[4] and TIME.search(r[4])]}
    json.dump(out, open(f"data/pyqdecode/verification_{g}.json", "w"), ensure_ascii=False, indent=1)
    return out


def md(o):
    L = [f"## {o['exam']}", "", "### Key provenance per paper", "",
         "| Paper | Year | Stage | Key status | Key document | Q | Deleted | Key matches APPSC doc | Changed by APPSC | No APPSC doc | 3rd-party conflict |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for p in o["papers"]:
        L.append(f"| {p['title'] or p['id']} | {p['year']} | {p['stage']} | {p['key_status']} | {p['key_doc_kind'] or '–'} | {p['Q']} | {p['deleted']} | "
                 f"{p['key_match']} | {p['key_changed']} | {p['no_official_doc']} | {p['third_party_conflict']} |")
    L += ["", f"### Questions deleted by APPSC ({len(o['deleted'])})", "", "Still analysed statement by statement; never counted as keyed.", ""]
    L += [f"- `{d['id']}` – {d['stem']}" for d in o["deleted"]]
    L += ["", f"### Key conflicts and disagreements ({len(o['conflicts'])})", "",
          "The published key is kept in every case; the note gives the competing fact and its source.", ""]
    L += [f"- `{c['id']}` – {c['stem']}  \n  Key: **{c['key']}**. {c['note']}" for c in o["conflicts"]]
    L += ["", f"### Statements not settled ({len(o['unresolved'])})", "",
          "Truth U (neither the key nor a reliable fact settles it) or basis 'pending'. Excluded from T/F percentages.", ""]
    L += [f"- `{u['id']}` {u['label']} [{u['truth']}/{u['basis']}] – {u['text']}" for u in o["unresolved"]]
    L += ["", f"### Time-sensitive facts ({len(o['time_sensitive'])})", "",
          "Facts true at the exam date that may have changed since; the manuals state the date the fact refers to.", ""]
    L += [f"- `{t['id']}` ({t['year']}) – {t['note']}" for t in o["time_sensitive"]]
    return "\n".join(L)


a, b = run("g1", "Group 1"), run("g2", "Group 2")
open("data/pyqdecode/VERIFICATION_REPORT.md", "w").write(
    "# PYQ Decoding Manuals – Stage 5 verification report\n\nGenerated by `tools/pyqdecode_verify.py` from `pyq.db` (official papers only).\n\n"
    + md(a) + "\n\n" + md(b) + "\n")
for o in (a, b):
    print(o["exam"], {k: len(v) for k, v in o.items() if isinstance(v, list)})
